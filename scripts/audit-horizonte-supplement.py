#!/usr/bin/env python3
"""Additional real API exercises for the frozen, fictional Horizonte case."""
import argparse
from copy import deepcopy
from hashlib import sha256
from io import BytesIO
import importlib.util
import json
from pathlib import Path
import zipfile


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--case', type=Path, required=True)
    parser.add_argument('--pdf', type=Path, required=True,
                        help='Existing PDF generated exclusively by report-gen.')
    parser.add_argument('--output', type=Path, required=True)
    args = parser.parse_args()
    runner = Path(__file__)
    runner_hash = sha256(runner.read_bytes()).hexdigest()
    spec = importlib.util.spec_from_file_location('horizonte_lifecycle', runner.with_name('audit-horizonte-lifecycle.py'))
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    journey = module.Journey(args.case, args.output)
    original = journey.load()
    original_hash = module.digest(args.case / 'engagement.yaml')
    journey.write_json('scope.json', {
        'schema': 'report-gen-horizonte-supplement/1', 'runner_sha256': runner_hash,
        'source_pdf': str(args.pdf.resolve()), 'source_pdf_sha256': module.digest(args.pdf),
        'generation': 'All delivered report formats are generated by report-gen APIs.',
        'scope': ['required_annex_blocks_delivery', 'native_pdf_annex', 'remove_root_cause_group',
                  'pending_severity', 'inference_and_hypothesis_claims']})

    # A missing mandatory annex must block an export, even with warnings acknowledged.
    name = 'informe-tecnico-base-sintetico.pdf'
    journey.project_call('POST', '/attachments/declare', body={'name': name, 'required': True})
    failed = journey.project_call('POST', '/delivery', body={
        'formats': ['html'], 'label': 'Entrega bloqueada de prueba', 'acknowledge_warnings': True}, expected=422)
    journey.write_json('missing-required-annex-rejection.json', failed.get_json())
    journey.check('Required missing PDF is named in the blocking error', name in failed.get_json()['error'])
    raw_pdf = args.pdf.read_bytes()
    journey.check('Annex is an existing real PDF output', raw_pdf.startswith(b'%PDF-'))
    uploaded = journey.project_call('POST', '/attachments/upload', data={
        'file': (BytesIO(raw_pdf), name)}).get_json()['data']
    annex = next(row for row in uploaded['attachments'] if row['name'] == name)
    journey.check('Uploaded PDF digest exactly matches the native report', annex['sha256'] == sha256(raw_pdf).hexdigest())
    journey.check('PDF upload still requires explicit inclusion and review', annex['reviewed'] is False and annex['include'] is False)
    journey.write_json('native-pdf-annex-scan.json', journey.project_call('GET', '/attachments/scan?uid=' + annex['uid']).get_json())
    annex.update(include=True, reviewed=True)
    journey.save(uploaded)

    # Match the product's delete-group behavior: unlink members without deleting findings.
    current = journey.load()
    expected = deepcopy(current['findings'])
    removed = current['root_cause_groups'][0]['uid']
    linked = [row['uid'] for row in current['findings'] if row.get('root_cause_uid') == removed]
    current['root_cause_groups'] = [row for row in current['root_cause_groups'] if row['uid'] != removed]
    for row in current['findings']:
        if row.get('root_cause_uid') == removed:
            row.pop('root_cause_uid')
    for row in expected:
        if row.get('root_cause_uid') == removed:
            row.pop('root_cause_uid')
    journey.save(current)
    reloaded = journey.load()
    journey.check('Removing group and its links preserves every finding field except that link', reloaded['findings'] == expected)
    journey.check('Deleted group has no dangling references', not any(row.get('root_cause_uid') == removed for row in reloaded['findings']))
    journey.write_json('removed-root-cause.json', {'removed_group_uid': removed, 'unlinked_finding_uids': linked,
                                                 'findings_preserved': len(expected)})

    finding = next(row for row in reloaded['findings'] if row['id'] == 'F01')
    for kind in ('inference', 'hypothesis'):
        journey.project_call('POST', '/insights', body={
            'action': 'set_claim', 'finding_uid': finding['uid'], 'kind': kind,
            'statement': 'Afirmación ' + kind + ' del escenario ficticio, pendiente de confirmación.',
            'demonstrates': 'Sólo la interpretación del guion y su documentación.',
            'does_not_demonstrate': 'No demuestra explotación, afectación ni riesgo de un banco real.',
            'evidence_uids': []})
    insight = journey.project_call('GET', '/insights').get_json()
    journey.check('Inference and hypothesis claims persist as distinct kinds',
                  {'inference', 'hypothesis'} <= {row['kind'] for row in insight['claims'] if row['finding_uid'] == finding['uid']})
    journey.write_json('inference-hypothesis-insights.json', insight)

    # Missing severity/score is the supported pending state; never mislabel it as informative.
    pending = journey.load()
    finding = next(row for row in pending['findings'] if row['id'] == 'F01')
    for field in ('severity', 'cvss', 'cvss_vector', 'cvss_version'):
        finding.pop(field, None)
    journey.save(pending)
    options = {'profile': 'technical', 'finding_uids': [finding['uid']],
               'section_keys': ['findings_summary', 'findings']}
    preview = journey.project_call('POST', '/audiences/preview', body=options).get_json()
    journey.write_json('pending-severity-preview.json', preview)
    journey.check('Pending severity remains exportable after explicit warning review',
                  not any(row['level'] == 'error' for row in preview['issues']))
    response = journey.project_call('POST', '/audiences/export', body={**options,
        'formats': ['pdf', 'docx', 'html', 'md'], 'label': 'Banco Horizonte · severidad pendiente · simulación',
        'acknowledge_warnings': True})
    path = journey.write('pending-severity-native-delivery.zip', response.data)
    with zipfile.ZipFile(path) as package:
        manifest = json.loads(package.read('verificacion.json'))
        entry = 'anexos/' + name
        journey.check('Declared PDF annex appears under its public delivery name', entry in manifest['files'])
        journey.check('Native PDF annex is included byte-for-byte in verified delivery', package.read(entry) == raw_pdf)
        journey.check('Native PDF annex retains declared hash in delivery manifest', manifest['files'][entry]['sha256'] == annex['sha256'])
        for member in package.infolist():
            if member.filename.endswith('.html'):
                journey.check('HTML counts the unclassified finding as a pending assessment', '1 pendiente de valoración' in package.read(member).decode())
            elif member.filename == 'informe.pdf':
                import fitz
                with fitz.open(stream=package.read(member), filetype='pdf') as pdf:
                    text = '\n'.join(page.get_text() for page in pdf)
                journey.check('PDF counts the unclassified finding as a pending assessment', '1 pendiente de valoración' in text)
            elif member.filename == 'informe.docx':
                from lxml import etree
                with zipfile.ZipFile(BytesIO(package.read(member))) as document:
                    tree = etree.fromstring(document.read('word/document.xml'))
                    text = ' '.join(tree.xpath('//*[local-name()="t"]/text()'))
                journey.check('DOCX counts the unclassified finding as a pending assessment', '1 pendiente de valoración' in text)
            elif member.filename == 'markdown.zip':
                with zipfile.ZipFile(BytesIO(package.read(member))) as markdown:
                    text = markdown.read('report.md').decode()
                journey.check('Markdown counts the unclassified finding as a pending assessment', '1 pendiente de valoración' in text)
        journey.write_json('pending-severity-delivery-manifest.json', manifest)
    journey.check('Frozen case remains exact and was never edited', module.digest(args.case / 'engagement.yaml') == original_hash)
    journey.check('Original copied source still contained all 27 findings', len(original['findings']) == 27)
    journey.check('Supplementary runner remained unchanged', sha256(runner.read_bytes()).hexdigest() == runner_hash)
    journey.check('Product sources remained unchanged', all(module.digest(module.ROOT / name) == value for name, value in journey.producer.items()))
    journey.flush(complete=True)
    print(json.dumps({'complete': True, 'checks': len(journey.records), 'output': str(journey.out)}))


if __name__ == '__main__':
    main()
