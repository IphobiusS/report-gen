#!/usr/bin/env python3
"""Real-browser report-library acceptance checks against an isolated local server."""
import argparse
import json
from pathlib import Path
import sys
import tempfile
import threading
from playwright.sync_api import sync_playwright

root=Path(__file__).resolve().parents[1];sys.path[:0]=[str(root),str(root/'webapp')]
import app as webapp
parser=argparse.ArgumentParser();parser.add_argument('--output',type=Path,required=True);args=parser.parse_args()
output=args.output.resolve();output.mkdir(parents=True,exist_ok=True)
checks=[];errors=[];outbound=[]
def check(name,value,detail=None):
    checks.append({'check':name,'passed':bool(value),'detail':detail})
    if not value: raise AssertionError(name+': '+str(detail))
def wait(page,expression):page.wait_for_function('()=>('+expression+')')
def ready(page):wait(page,'S.slug && !projectStore.loading')
def field(d,key):return d.locator('[data-design-field="'+key+'"]')

with tempfile.TemporaryDirectory(prefix='design-browser-') as temp:
    webapp.PROJECTS=Path(temp)/'projects';webapp.PROJECTS.mkdir()
    webapp.app.config['LIBRARY_PATH']=str(Path(temp)/'findings.json')
    webapp.app.config['DESIGN_LIBRARY_PATH']=str(Path(temp)/'designs.json')
    server=webapp.create_local_server(0);thread=threading.Thread(target=server.run,daemon=True);thread.start()
    base=f'http://127.0.0.1:{server.effective_port}'
    try:
      with sync_playwright() as pw:
        browser=pw.chromium.launch();ctx=browser.new_context(viewport={'width':1366,'height':1000},reduced_motion='reduce')
        ctx.on('request',lambda r:outbound.append(r.url) if not r.url.startswith((base+'/', 'blob:', 'data:', 'about:')) else None)
        page=ctx.new_page();page.on('pageerror',lambda e:errors.append(str(e)))
        page.goto(base);page.locator('#splash').wait_for(state='hidden')
        welcome=page.get_by_role('button',name='Abrir biblioteca de informes',exact=True)
        welcome.click();opening=page.get_by_role('dialog',name='Biblioteca de informes',exact=True);opening.wait_for(state='visible')
        page.keyboard.press('Escape');opening.wait_for(state='detached');wait(page,"document.activeElement.textContent==='Abrir biblioteca de informes'")
        check('Welcome library returns focus to its own opener',welcome.evaluate('(e)=>e===document.activeElement'))
        page.get_by_role('button',name='Probar Nimbus',exact=True).click();ready(page)
        baseline=page.evaluate('structuredClone(S.data)');demo=page.evaluate('S.slug')
        page.locator('#designLibraryBtn').click();gal=page.get_by_role('dialog',name='Biblioteca de informes',exact=True);gal.wait_for(state='visible')
        check('14 OffSec profiles',gal.locator('[data-design]').count()==14)
        gal.locator('[data-design="offsec-oswe"]').click()
        gal.locator('.design-preview img').wait_for(state='visible')
        wait(page,"[...document.querySelectorAll('.design-preview img')].every(i=>i.complete&&i.naturalWidth>0)")
        check('Real cover preview loaded',gal.locator('.design-preview img').evaluate('(i)=>i.naturalWidth>0'))
        gal.get_by_label('Variante de diseño').select_option('quiet')
        check('Quiet preview is a distinct export','quiet-cover' in gal.locator('.design-preview img').get_attribute('src'))
        gal.get_by_role('button',name='Técnica',exact=True).click()
        check('Technical page available','quiet-technical' in gal.locator('.design-preview img').get_attribute('src'))
        page.screenshot(path=str(output/'gallery-offsec.png'))
        gal.get_by_role('button',name='Aplicar apariencia',exact=True).click()
        wait(page,"S.data.meta.design?.id==='offsec-oswe'&&!projectStore.loading")
        actual=page.evaluate('structuredClone(S.data)');actual['meta'].pop('design');actual['meta']['theme']=baseline['meta']['theme']
        check('Applying appearance preserves full Nimbus data',actual==baseline)
        check('Applying appearance keeps project identity',page.evaluate('S.slug')==demo)
        page.locator('#designLibraryBtn').click();gal=page.get_by_role('dialog',name='Biblioteca de informes',exact=True);gal.wait_for(state='visible')
        gal.locator('[data-family="HTB"]').click();check('8 HTB profiles',gal.locator('[data-design]').count()==8)
        gal.get_by_label('Buscar plantillas').fill('Wi-Fi');check('Search matches Wi-Fi course',gal.locator('[data-design]').count()==1 and gal.locator('[data-design]').get_attribute('data-design')=='htb-cwpe')
        gal.get_by_label('Buscar plantillas').fill('');gal.locator('[data-design="htb-cwee"]').click()
        check('CWEE encryption limitation visible','no cifra' in gal.inner_text())
        gal.get_by_role('button',name='Crear proyecto',exact=True).click();new=page.get_by_role('dialog',name='Nuevo proyecto desde plantilla',exact=True)
        field(new,'project-title').fill('CWEE audit English');field(new,'lang').select_option('en');new.get_by_role('button',name='Crear proyecto',exact=True).click()
        wait(page,"S.data.meta.report_title==='CWEE audit English'&&!projectStore.loading")
        check('English starter has correct language',page.evaluate("S.data.meta.lang==='en'&&S.data.report.sections[0].title==='Work summary'"))
        check('Starter has no invented findings',page.evaluate('S.data.findings.length===0'))
        page.locator('#deliveryBtn').click();delivery=page.get_by_role('dialog',name='Preparar entrega',exact=True);delivery.wait_for(state='visible')
        check('CWEE defaults to Markdown only',delivery.locator('[data-delivery-format]:checked').evaluate_all('(xs)=>xs.map(x=>x.value)')==['md'])
        check('Delivery carries actual exam guidance','does not encrypt' in delivery.inner_text())
        page.keyboard.press('Escape')
        page.locator('#designLibraryBtn').click();gal=page.get_by_role('dialog',name='Biblioteca de informes',exact=True);gal.wait_for(state='visible')
        gal.locator('[data-family="HTB"]').click();gal.locator('[data-design="htb-cpts"]').click();gal.get_by_label('Variante de diseño').select_option('quiet');gal.get_by_role('button',name='Duplicar y personalizar',exact=True).click()
        custom=page.get_by_role('dialog',name='Personalizar plantilla',exact=True)
        field(custom,'name').fill('Aurora personal');field(custom,'accent').fill('#245680');field(custom,'layout').select_option('frame')
        custom.get_by_role('button',name='Añadir sección',exact=True).click();custom.locator('.design-section-row input').last.fill('Apéndice propio')
        custom.get_by_role('button',name='Actualizar vista previa',exact=True).click();custom.locator('iframe').wait_for(state='visible')
        page.screenshot(path=str(output/'custom-preview.png'))
        check('Custom preview preserves quiet selection',custom.locator('iframe').get_attribute('srcdoc').find('--cover-rule:#4B5E72')>=0)
        frame=custom.locator('iframe').element_handle().content_frame()
        check('Custom preview contains the real provider logo',frame.locator('.provider-logo[aria-label="Hack The Box"] svg').count()==1)
        check('Custom preview loads the report font',frame.evaluate('async()=>{await document.fonts.ready;return document.fonts.check(\'700 32pt \"Report Cover\"\')}'))
        custom.get_by_role('button',name='Guardar plantilla',exact=True).click();custom.wait_for(state='detached')
        gal.locator('[data-design^="custom-"]').wait_for(state='visible')
        check('Personal design appears in gallery',gal.locator('[data-design^="custom-"]').count()==1)
        gal.locator('[data-design^="custom-"]').click();gal.get_by_role('button',name='Crear proyecto',exact=True).click();new=page.get_by_role('dialog',name='Nuevo proyecto desde plantilla',exact=True)
        field(new,'project-title').fill('Personal audit');new.get_by_role('button',name='Crear proyecto',exact=True).click()
        wait(page,"S.data.meta.report_title==='Personal audit'&&!projectStore.loading")
        saved=page.evaluate('structuredClone(S.data.meta.design)');personal_slug=page.evaluate('S.slug')
        check('Saved personal appearance applied',saved['accent']=='#245680' and saved['layout']=='frame')
        check('Quiet personal variant survives project creation',saved['variant']=='quiet')
        check('Custom section retained',page.evaluate("S.data.report.sections.some(s=>s.title==='Apéndice propio')"))
        page.locator('#designLibraryBtn').click();gal=page.get_by_role('dialog',name='Biblioteca de informes',exact=True);gal.wait_for(state='visible')
        gal.locator('[data-family="Personal"]').click();gal.locator('[data-design^="custom-"]').click();gal.get_by_role('button',name='Editar plantilla',exact=True).click();custom=page.get_by_role('dialog',name='Personalizar plantilla',exact=True)
        field(custom,'accent').fill('#c12448');custom.get_by_role('button',name='Guardar plantilla',exact=True).click();custom.wait_for(state='detached')
        check('Editing library does not change open project',page.evaluate('S.data.meta.design')==saved)
        gal.get_by_role('button',name='Eliminar plantilla',exact=True).click();confirm=page.get_by_role('dialog',name='Eliminar plantilla personal',exact=True);confirm.get_by_role('button',name='Confirmar eliminación',exact=True).click();confirm.wait_for(state='detached')
        check('Deleting design preserves project snapshot',page.evaluate('S.data.meta.design')==saved)
        gal.locator('[data-family="General"]').click();check('Six legacy designs remain',gal.locator('[data-design]').count()==6)
        gal.locator('[data-family="Históricas"]').click();check('Historical catalog separates non-current profiles',gal.locator('.design-history').count()==3)
        page.keyboard.press('Escape');gal.wait_for(state='detached');wait(page,"document.activeElement.id==='designLibraryBtn'");check('Escape returns focus',page.locator('#designLibraryBtn').evaluate('(e)=>e===document.activeElement'))
        page.set_viewport_size({'width':390,'height':844});page.locator('#designLibraryBtn').click();gal=page.get_by_role('dialog',name='Biblioteca de informes',exact=True);gal.wait_for(state='visible')
        gal.locator('[data-design="offsec-oscp"]').click()
        check('Mobile dialog fits viewport',gal.evaluate('(e)=>e.getBoundingClientRect().right<=innerWidth&&e.scrollWidth<=e.clientWidth+1'))
        check('Mobile preview fits panel',gal.locator('.design-detail').evaluate('(e)=>e.scrollWidth<=e.clientWidth+1'))
        page.screenshot(path=str(output/'gallery-mobile.png'))
        page.keyboard.press('Escape');page.set_viewport_size({'width':1366,'height':1000});page.reload();page.locator('#splash').wait_for(state='hidden');ready(page)
        page.locator('#projectSelect').select_option(personal_slug);wait(page,"S.slug==="+json.dumps(personal_slug)+"&&!projectStore.loading")
        check('Snapshot survives application reload',page.evaluate('S.data.meta.design')==saved)
        html=page.evaluate("async()=>{const r=await api.post('/api/design-library/preview',{design:S.data.meta.design});return r.text();}")
        check('Deleted personal source retains provider logo', 'aria-label="Hack The Box"' in html)
        for attempt in range(3):
            page.locator('#designLibraryBtn').click();again=page.get_by_role('dialog',name='Biblioteca de informes',exact=True);again.wait_for(state='visible')
            page.keyboard.press('Escape');again.wait_for(state='detached');wait(page,"document.activeElement.id==='designLibraryBtn'")
            check('Repeated keyboard focus return '+str(attempt+1),page.locator('#designLibraryBtn').evaluate('(e)=>e===document.activeElement'))
        check('No JavaScript errors',not errors,errors);check('No external requests',not outbound,outbound)
        browser.close()
    finally:
      server.close();(output/'browser-checks.json').write_text(json.dumps(checks,ensure_ascii=False,indent=2)+'\n')
print(str(len(checks))+' browser checks PASS')
