"""Explicit backend error prose; opaque values are formatted after translation.

The default retains historical Spanish (including legacy bilingual literals).
Request selection and worker scopes do not change the report language. Unknown
third-party details are returned verbatim, never translated by replacement.
"""
from contextlib import contextmanager
from contextvars import ContextVar
from functools import wraps
from inspect import signature

_LANGUAGE = ContextVar('report_gen_error_language', default='es')


def normalized_language(value):
    return value if value in ('es', 'en') else 'es'


def current_language():
    return _LANGUAGE.get()


def set_language(value):
    return _LANGUAGE.set(normalized_language(value))


def reset_language(token):
    _LANGUAGE.reset(token)


@contextmanager
def language_scope(value):
    token = set_language(value)
    try:
        yield
    finally:
        reset_language(token)


def message(source, *, en=None, language=None, **parameters):
    """Select an authored template before inserting values, preserving each value.

    Unknown templates use their original prose. `en` is an explicit source-owned
    alternative for newly introduced messages; it never derives from user data.
    """
    selected = current_language() if language is None else normalized_language(language)
    template = (en if en is not None else CATALOG.get(source, source)) if selected == 'en' else source
    return template.format(**parameters)


def language_argument(function):
    """Scope an existing explicit `lang` parameter for nested error helpers."""
    parameters = signature(function)
    @wraps(function)
    def localized(*args, **kwargs):
        bound = parameters.bind(*args, **kwargs)
        selected = current_language() if 'lang' not in bound.arguments else normalized_language(bound.arguments['lang'])
        bound.arguments['lang'] = selected
        with language_scope(selected):
            return function(*bound.args, **bound.kwargs)
    return localized


